import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Sets default <title> and <meta name="description"> for all pages
// Can be overridden per page
export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// Required root component in the App Router
// Wraps every page in the app
// Purpose: 
// Global structure: provides the HTML shell for all pages
// Typography: loads and applies fonts site-wide
// SEO: sets default metadata
// Styling: applies global CSS classes
export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        {children}
      </body>
    </html>
  );
}
